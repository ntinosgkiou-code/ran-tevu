def build_system_prompt(business: dict, assistant_name: str = "Madlen") -> str:
    """Συνθέτει πλήρες system prompt για ένα business.
    business: dict with keys: name, type, address, services (list of dicts),
              hours (dict by day), etc."""
    bt = (business.get("type") or "default").lower()

    # Map common terms → industry keys
    type_map = {
        "οδοντιατρείο": "dental", "dental": "dental",
        "αισθητική": "beauty", "beauty": "beauty", "spa": "beauty",
        "κομμωτήριο": "hair", "hair": "hair",
        "κτηνιατρείο": "vet", "vet": "vet", "veterinary": "vet",
        "φυσιοθεραπεία": "physio", "physio": "physio", "φυσικοθεραπ": "physio",
        # ιατρεία (generic medical) — ο κύριος στόχος· κάθε ειδικότητα πέφτει εδώ
        "ιατρείο": "medical", "ιατρικ": "medical", "γιατρ": "medical", "ιατρός": "medical",
        "doctor": "medical", "clinic": "medical", "κλινικ": "medical", "medical": "medical",
        "καρδιολ": "medical", "παθολ": "medical", "δερματολ": "medical", "παιδίατρ": "medical",
        "γυναικολ": "medical", "ορθοπ": "medical", "νευρολ": "medical", "ενδοκριν": "medical",
        "ουρολ": "medical", "οφθαλμ": "medical", "ωτορ": "medical", "διαιτολ": "medical",
        "ψυχολ": "medical", "ψυχιατρ": "medical", "λογοθερ": "medical", "μικροβιολ": "medical",
        "εστιατόριο": "restaurant", "restaurant": "restaurant",
        "γυμναστήριο": "fitness", "fitness": "fitness",
        "pilates": "fitness", "yoga": "fitness", "gym": "fitness",
    }
    industry = "default"
    for k, v in type_map.items():
        if k in bt:
            industry = v
            break

    template = INDUSTRY_PROMPTS.get(industry, INDUSTRY_PROMPTS["default"])

    # Format services
    services = business.get("services", [])
    if isinstance(services, str):
        try:
            import json as _json
            services = _json.loads(services)
        except Exception:
            services = []
    services_text = "\n".join(
        f"- {s.get('name', '')}: {s.get('duration', '?')} λεπτά, €{s.get('price', '?')}"
        for s in (services or [])
        if isinstance(s, dict)
    ) or "(Δες ιστοσελίδα για πλήρη λίστα)"

    # Format hours
    hours = business.get("hours", {})
    if isinstance(hours, str):
        try:
            import json as _json
            hours = _json.loads(hours)
        except Exception:
            hours = {}
    days_gr = {
        "monday": "Δευτέρα", "tuesday": "Τρίτη", "wednesday": "Τετάρτη",
        "thursday": "Πέμπτη", "friday": "Παρασκευή",
        "saturday": "Σάββατο", "sunday": "Κυριακή",
    }
    hours_text = "\n".join(
        f"- {days_gr.get(d, d)}: {h}"
        for d, h in (hours or {}).items()
    ) or f"{business.get('day_start', '10:00')} - {business.get('day_end', '20:00')}"

    body = template.format(
        assistant_name=assistant_name,
        business_name=business.get("name", "η επιχείρηση"),
        address=business.get("address", "—"),
        services_list=services_text,
        hours=hours_text,
    )

    # Inject custom tone
    tone = business.get("voice_tone", "friendly")
    tone_guide = TONE_GUIDELINES.get(tone, TONE_GUIDELINES["friendly"])

    # Inject custom owner instructions (e.g. "πάντα ρώτα αν είναι πρώτη φορά",
    # "μην κλείνεις ραντεβού με ζώο < 3 μηνών", "η κλινική κλείνει τον Αύγουστο")
    custom = (business.get("voice_custom_instructions") or "").strip()
    custom_section = ""
    if custom:
        custom_section = (
            "\n\n══════ ΕΙΔΙΚΕΣ ΟΔΗΓΙΕΣ ΑΠΟ ΤΟΝ ΙΔΙΟΚΤΗΤΗ "
            "(ΥΨΗΛΗ ΠΡΟΤΕΡΑΙΟΤΗΤΑ — υπερισχύουν αν συγκρούονται με τα άλλα) ══════\n"
            f"{custom}\n"
        )

    return (
        UNIVERSAL_GUIDELINES + "\n\n" +
        tone_guide + "\n\n" +
        body +
        custom_section
    )


def build_first_message(business: dict, assistant_name: str = "Madlen") -> str:
    """Το πρώτο μήνυμα που ακούει ο πελάτης μόλις απαντηθεί η κλήση.
    Αν business.voice_greeting είναι set, χρησιμοποιεί αυτό· αλλιώς το default after-hours
    greeting που πιάνει τις χαμένες κλήσεις → άμεση λίστα αναμονής / επόμενο ραντεβού."""
    custom = (business.get("voice_greeting") or "").strip()
    if custom:
        return custom
    return (
        "Γεια σας. Το ιατρείο μας αυτή τη στιγμή είναι κλειστό. Αν θέλετε να μπείτε σε άμεση "
        "λίστα αναμονής ή να κλείσετε το επόμενο διαθέσιμο ραντεβού, μην κλείσετε το τηλέφωνο. "
        "Σε 3 δευτερόλεπτα θα συνδεθείτε με τον ψηφιακό μας βοηθό που θα καταχωρήσει το αίτημά σας αμέσως."
    )


